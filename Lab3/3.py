import numpy as np
import sys

class SimplexSolver:
    def __init__(self):
        # Список для хранения всех симплекс-таблиц (история шагов).
        # Нужен для проверки на зацикливание: если новая таблица совпадает со старой, значит, мы ходим по кругу
        self.tableaux = [] 
        # Счетчик итераций (шагов алгоритма). Изначально 0
        self.iteration = 0 
        # Максимальное количество итераций
        self.max_iterations = 100 
        # Список для отслеживания базисных переменных на каждом шаге.
        # Например, на первом шаге базисными могут быть x3 и x4, на втором — x2 и x3
        self.basic_vars = []  
        # Имена всех переменных (x1, x2, x3...). Заполняется при загрузке данных
        self.all_vars = []   
        # Флаг, который показывает, найдено ли решение. Изначально False (решение еще не найдено)
        self.no_solution = False 
        
    def load_from_csv(self, filename):
        # Загружает данные задачи из CSV-файла
        # Первая строка: тип задачи (max или min)
        # Вторая строка: коэффициенты целевой функции
        # Последующие строки: матрица ограничений (последний столбец - свободные члены)
        try:
            # Открываем файл для чтения с кодировкой UTF-8.
            with open(filename, 'r', encoding='utf-8') as f:
                lines = f.readlines()
        except FileNotFoundError:
            # Если файл не найден, выводим ошибку и завершаем программу
            print(f"Ошибка: Файл {filename} не найден!")
            sys.exit(1)
           
        # Удаляем символы новой строки и пробелы
        lines = [line.strip() for line in lines if line.strip()]
        
        # Определяем тип задачи: 'max' (максимизация) или 'min' (минимизация)
        problem_type = lines[0].strip().lower() # Метод lower() в Python переводит все заглавные буквы в строке в нижний регистр
        # Создаем булеву переменную: True, если максимизация, и False, если минимизация
        maximize = (problem_type == 'max')
        # Читаем коэффициенты целевой функции из второй строки.
        # Например, "1,3" превратится в [1.0, 3.0]
        c_values = [float(x) for x in lines[1].split(',')]
        # Преобразуем список в массив NumPy для удобства математических операций
        c = np.array(c_values)
        # Количество исходных переменных
        n_vars = len(c)
        
        # Создаем имена переменных: x1, x2, ... для основных переменных.
        # Это нужно для красивого вывода таблицы
        self.all_vars = [f'x{i+1}' for i in range(n_vars)]
        
        # Матрица ограничений. Сюда будем складывать строки из файла
        constraints_data = []
        # Проходим по всем строкам, начиная с третьей (индекс 2)
        for i in range(2, len(lines)):
            # Разбиваем строку по запятой и преобразуем в числа
            row = [float(x) for x in lines[i].split(',')]
            # Проверяем, что количество элементов в строке соответствует ожидаемому.
            # Должно быть n_vars коэффициентов + 1 свободный член
            if len(row) != n_vars + 1:
                print(f"Ошибка: Строка {i+1} должна содержать {n_vars + 1} элементов, а содержит {len(row)}")
                sys.exit(1)
            constraints_data.append(row)
        # Преобразуем список строк в матрицу NumPy
        constraints_array = np.array(constraints_data)
        # Разделяем матрицу на две части:
        # A — матрица коэффициентов при переменных (все столбцы, кроме последнего)
        A = constraints_array[:, :-1] 
        # b — вектор свободных членов (последний столбец)
        b = constraints_array[:, -1] 
        
        # Добавляем имена дополнительных (искусственных) переменных.
        # В классическом симплекс-методе для каждого ограничения вида <= добавляется своя переменная.
        # Например, если у нас 2 ограничения и 2 исходные переменные, добавятся x3 и x4
        m_constraints = len(b)
        for i in range(m_constraints):
            self.all_vars.append(f'x{n_vars + i + 1}')

        # Возвращаем все необходимые данные для решения задачи
        return A, b, c, maximize
    
    # Основной метод, который реализует алгоритм симплекс-метода
    def solve(self, A, b, c, maximize=True):

        # Сбрасываем счетчики и историю перед новым решением
        self.iteration = 0
        self.tableaux = []
        self.basic_vars = []

        # Получаем размеры матрицы A: m — количество ограничений, n — количество переменных
        m, n = A.shape
        
        # Если задача на минимизацию, мы преобразуем её в задачу на максимизацию.
        # Для этого умножаем коэффициенты целевой функции на -1.
        # Это стандартный прием: минимизировать F — то же самое, что максимизировать -F
        if not maximize:
            c = -c
        
        # Создаем начальную симплекс-таблицу.
        # Размер: (m + 1) строк (ограничения + строка целевой функции) 
        # и (n + m + 1) столбцов (свободный член + исходные переменные + дополнительные переменные)
        table = np.zeros((m + 1, n + m + 1))
        
        # Заполняем ограничения в таблице
        for i in range(m):
            # Столбец 0 — свободные члены (правая часть ограничений)
            table[i, 0] = b[i]  
            # Срез table[i, 1:n+1] выбирает в i-й строке столбцы с 1 по n включительно
            # Эти n столбцов отведены под коэффициенты при исходных переменных x1, x2, ..., xn.
            # A[i, :] — вся i-я строка матрицы ограничений A, содержащая эти коэффициенты.
            # Таким образом, мы копируем коэффициенты из A в соответствующие столбцы таблицы
            table[i, 1:n+1] = A[i, :] 
            # Добавляем единичную матрицу для дополнительных переменных.
            # Для каждого i-го ограничения вводится своя дополнительная переменная
            # Номер её столбца вычисляется как n + i + 1 (n — число исходных переменных, i — номер ограничения).
            # Например, при n=2: для i=0 это столбец 3 (x3), для i=1 — столбец 4 (x4).
            # Ставим в этом столбце 1, чтобы дополнительная переменная вошла в базис с коэффициентом 1.
            # Остальные столбцы дополнительных переменных в этой строке остаются нулями (таблица изначально нулевая)
            table[i, n + i + 1] = 1 
        
        # Заполняем строку целевой функции (последняя строка с индексом m).
        # Срез table[m, 1:n+1] выбирает столбцы с 1 по n — места для исходных переменных.
        # Записываем туда коэффициенты целевой функции с противоположным знаком: -c.
        table[m, 1:n+1] = -c  # коэффициенты с противоположным знаком
        
        # Инициализируем список базисных переменных для начальной таблицы.
        # На первом шаге базисными являются дополнительные переменные: x_{n+1}, x_{n+2}, ..., x_{n+m}.
        # Формула f'x{n+i+1}' создаёт имена: например, при n=2 и m=2 получим ['x3', 'x4']
        initial_basis = [f'x{n+i+1}' for i in range(m)]
        # Сохраняем этот список в историю базисов
        self.basic_vars.append(initial_basis)
        
        # Сохраняем копию начальной таблицы в историю всех таблиц.
        # Копия нужна, чтобы потом можно было проверить зацикливание (сравнить текущую таблицу с предыдущими)
        self.tableaux.append(table.copy())

        # Выводим начальную симплекс-таблицу на экран для наглядности
        print("Начальная таблица")
        self.print_table(table, self.iteration)

        # Основной цикл симплекс-метода
        # Цикл выполняется, пока не достигнуто максимальное число итераций
        while self.iteration < self.max_iterations:
            # Увеличиваем счётчик итераций
            self.iteration += 1
            # Выводим номер текущей итерации
            print(f"\nИтерация {self.iteration}")
            
            # Проверяем критерий оптимальности:
            # для максимизации — все коэффициенты в строке F >= 0,
            # для минимизации — все коэффициенты <= 0.
            # Метод is_optimal сам выбирает нужное условие в зависимости от параметра maximize
            if self.is_optimal(table, maximize):
                print("Критерий оптимальности выполнен")
                break
            
            # Разрешающий столбец определяет переменную, которую выгодно ввести в базис,
            # чтобы улучшить текущее решение.
            # Для задачи максимизации выбирается столбец с наименьшим (самым отрицательным)
            # коэффициентом в строке целевой функции F.
            # Для задачи минимизации — с наибольшим (самым положительным) коэффициентом
            pivot_col = self.find_pivot_column(table, maximize)

            # Если разрешающий столбец не найден (возвращён None), это означает,
            # что все коэффициенты в строке F уже удовлетворяют критерию оптимальности
            if pivot_col is None:
                print("Не удалось найти разрешающий столбец")
                self.no_solution = True
                break

            # Получаем имя переменной, которая будет введена в базис (например, 'x2').
            # get_var_name преобразует индекс столбца в понятное имя.
            entering_var = self.get_var_name(pivot_col, n)
            print(f"Вводимая переменная: {entering_var} (столбец {pivot_col})")
            
            # Разрешающая строка определяется по минимальному оценочному отношению:
            # свободный член делится на положительный элемент разрешающего столбца.
            # Эта строка показывает, какая переменная должна покинуть базис (стать равной нулю),
            # потому что соответствующий ресурс исчерпан.
            pivot_row = self.find_pivot_row(table, pivot_col)

            if pivot_row is None:
                print("Задача не имеет конечного оптимального решения (F = ∞)")
                self.no_solution = True
                break

            # Определяем, какая переменная выводится из базиса.
            # self.basic_vars[-1] — это список базисных переменных на текущей итерации.
            # pivot_row — индекс строки, соответствующей выводимой переменной
            leaving_var = self.basic_vars[-1][pivot_row]
            print(f"Выводимая переменная: {leaving_var} (строка {pivot_row})")
            print(f"Разрешающий элемент: [{pivot_row}, {pivot_col}] = {table[pivot_row, pivot_col]:.3f}")
            
            # Выполняем преобразование Жордана-Гаусса
            # Метод pivot пересчитывает всю таблицу:
            #  1) разрешающую строку делит на разрешающий элемент, чтобы на его месте получить 1;
            #  2) из всех остальных строк вычитает новую разрешающую строку, умноженную
            # на соответствующий коэффициент, чтобы обнулить разрешающий столбец
            table = self.pivot(table, pivot_row, pivot_col)
            
            # Обновляем базисные переменные
            # Берём предыдущий базис (последний в списке self.basic_vars) и делаем его копию
            new_basis = self.basic_vars[-1].copy()
            # Заменяем переменную, которая вышла из базиса, на переменную, которая вошла
            new_basis[pivot_row] = entering_var
            # Добавляем обновлённый базис в историю
            self.basic_vars.append(new_basis)
            
            # Сохраняем таблицу
            self.tableaux.append(table.copy())
            
            # Проверяем на зацикливание
            # Метод check_cycling сравнивает текущую таблицу со всеми предыдущими.
            # Если найдено совпадение (с заданной точностью), значит, алгоритм зациклился
            if self.check_cycling():
                print("Обнаружено зацикливание!")
                self.no_solution = True
                break

            # выводим таблицу
            self.print_table(table, self.iteration)
        else:
            print("Достигнуто максимальное количество итераций")
            self.no_solution = True

        # Возвращаем последнюю симплекс-таблицу (даже если решение не оптимально)
        return table

    # Возвращает понятное имя переменной по индексу столбца в таблице.
    # Например, если col_index = 1, вернёт имя первой исходной переменной (обычно 'x1')
    # Возвращает имя переменной по индексу столбца
    def get_var_name(self, col_index, n_vars):
        # Столбец 0 — это свободные члены, у него нет имени переменной.
        # Возвращаем условное обозначение "B" (Basis / свободный член)
        if col_index == 0:
            return "B"
        # Если индекс в пределах списка всех переменных, возвращаем имя из self.all_vars.
        # self.all_vars[col_index - 1], потому что индексация списка начинается с 0,
        # а столбцы таблицы — с 1 (столбец 0 занят свободными членами)
        elif 1 <= col_index <= len(self.all_vars):
            return self.all_vars[col_index - 1]
        else:
            # Если индекс выходит за пределы списка,
            # возвращаем имя вида 'x{col_index}'
            return f"x{col_index}"
    
    def is_optimal(self, table, maximize):
        # Проверяет, достигнут ли критерий оптимальности.
        # Для этого анализируется последняя строка таблицы (строка целевой функции F),
        # начиная со второго столбца (индекс 1), чтобы исключить столбец свободных членов
        last_row = table[-1, 1:]  
        # Для задачи максимизации решение оптимально, если все коэффициенты
        # в строке F неотрицательны (>= 0)
        if maximize:
            return np.all(last_row >= -1e-10)
        # Для задачи минимизации решение оптимально, если все коэффициенты
        # в строке F неположительны (<= 0)
        else:
            return np.all(last_row <= 1e-10)

    # Находит разрешающий столбец — столбец, который определяет переменную,
    # вводимую в базис для улучшения решения
    def find_pivot_column(self, table, maximize):
        # Находит разрешающий столбец
        last_row = table[-1, 1:]  # строка целевой функции без свободного члена
        
        if maximize:
            # Для максимизации ищем столбцы с отрицательными коэффициентами в строке F.
            # Отрицательный коэффициент означает, что увеличение этой переменной
            # приведёт к росту целевой функции
            negative_indices = np.where(last_row < -1e-10)[0]
            # Если отрицательных нет, все коэффициенты >= 0 — решение оптимально,
            # разрешающий столбец отсутствует
            if len(negative_indices) == 0:
                return None
            
            # Среди отрицательных выбираем столбец с наименьшим (самым отрицательным)
            # значением, так как он обеспечивает наибольший прирост F на единицу изменения.
            # np.argmin возвращает индекс минимального элемента в подмассиве,
            # затем прибавляем 1, чтобы перейти к индексации столбцов таблицы (0 — свободный член)
            pivot_col = negative_indices[np.argmin(last_row[negative_indices])] + 1
        else:
            # Для минимизации ищем столбцы с положительными коэффициентами в строке F.
            # Положительный коэффициент означает, что увеличение переменной увеличивает
            # затраты, а нам нужно их снижать. Выбираем наибольший положительный,
            # чтобы быстрее уменьшить целевую функцию
            positive_indices = np.where(last_row > 1e-10)[0]
            # Если положительных нет, все коэффициенты <= 0 — решение оптимально
            if len(positive_indices) == 0:
                return None
            # Выбираем столбец с наибольшим значением
            pivot_col = positive_indices[np.argmax(last_row[positive_indices])] + 1
        
        return pivot_col

    # Находит разрешающую строку по правилу минимального оценочного отношения.
    # Оценочное отношение = свободный член / положительный элемент разрешающего столбца
    def find_pivot_row(self, table, pivot_col):
        # Количество строк ограничений (без строки F)
        m = table.shape[0] - 1
        
        min_ratio = float('inf') # начальное значение — бесконечность
        pivot_row = None # пока не найдена
        
        for i in range(m):
            if table[i, pivot_col] > 1e-10:  # Делить можно только на положительные элементы
                 # Вычисляем оценочное отношение: свободный член / коэффициент в столбце
                ratio = table[i, 0] / table[i, pivot_col]
                 # Выбираем минимальное неотрицательное отношение
                if ratio >= 0 and ratio < min_ratio - 1e-10:
                    min_ratio = ratio
                    pivot_row = i
        
        return pivot_row
    
    # Выполняет преобразование Жордана-Гаусса для перехода к новому базисному решению
    # Суть: разрешающую строку делим на разрешающий элемент, чтобы на его месте получить 1.
    # Затем из всех остальных строк вычитаем новую разрешающую строку, умноженную
    # на соответствующий коэффициент, чтобы обнулить весь разрешающий столбец
    def pivot(self, table, pivot_row, pivot_col):

        new_table = table.copy() # работаем с копией, чтобы не портить исходную таблицу
        pivot_element = table[pivot_row, pivot_col] # разрешающий элемент
        
        # Нормализуем разрешающую строку: делим все её элементы на разрешающий элемент.
        # Теперь на месте pivot_element стоит 1
        new_table[pivot_row, :] = table[pivot_row, :] / pivot_element
        
        # Обновляем все остальные строки (включая строку целевой функции F)
        for i in range(table.shape[0]):
            if i != pivot_row: # пропускаем саму разрешающую строку
                # Коэффициент, на который нужно умножить новую разрешающую строку,
                # чтобы при вычитании обнулить элемент в разрешающем столбце
                factor = table[i, pivot_col] / pivot_element
                # Вычитаем: новая строка = старая строка - factor * новая разрешающая строка
                new_table[i, :] = table[i, :] - factor * table[pivot_row, :]
        
        return new_table

    # Проверяет, не зациклился ли алгоритм.
    # Зацикливание — редкая ситуация, когда из-за вырожденности алгоритм
    # бесконечно перебирает одни и те же базисы, не улучшая целевую функцию.
    # Признак: текущая симплекс-таблица уже встречалась ранее
    def check_cycling(self):
        # Если таблиц меньше трёх, проверять нечего (не с чем сравнивать)
        if len(self.tableaux) < 3:
            return False
        
        current = self.tableaux[-1] # текущая (последняя) таблица
        # Сравниваем текущую таблицу со всеми предыдущими, кроме двух последних.
        # range(len(self.tableaux) - 2) даёт индексы от 0 до len-3
        for i in range(len(self.tableaux) - 2):
            # np.allclose сравнивает массивы поэлементно с заданной точностью.
            # atol=1e-6 — абсолютная погрешность; если все элементы совпадают
            # в пределах этой погрешности, таблицы считаются одинаковыми
            if np.allclose(current, self.tableaux[i], atol=1e-6):
                return True
        
        return False  # зацикливания нет

    # Выводит симплекс-таблицу в читаемом виде.
    # table — матрица чисел, tableau_index — номер итерации (для доступа к базису)
    def print_table(self, table, tableau_index):
        # Выводит одну симплекс-таблицу
        m, n = table.shape
        
        # Заголовок таблицы
        headers = ["Базис", "Св.член"]
        headers.extend(self.all_vars)
        
        # Выводим заголовок
        header_line = " | ".join(f"{header:>10}" for header in headers)
        print(header_line)
        print("-" * len(header_line))
        
        # Выводим строки ограничений
        basis_vars = self.basic_vars[tableau_index]
        
        for i in range(m - 1):
            if i < len(basis_vars):
                row_name = basis_vars[i]
                row = [row_name, f"{table[i, 0]:.3f}"]
                row.extend(f"{table[i, j]:.3f}" for j in range(1, n))
                print(" | ".join(f"{item:>10}" for item in row))
        
        # Выводим целевую функцию
        row = ["F", f"{table[m-1, 0]:.3f}"]
        row.extend(f"{table[m-1, j]:.3f}" for j in range(1, n))
        print(" | ".join(f"{item:>10}" for item in row))
        
        # Выводим текущий базис
        print(f"Текущий базис: {', '.join(basis_vars)}")

    # Извлекает значения переменных и оптимум из финальной симплекс-таблицы
    def get_solution(self, table, maximize=True):
        
        solution = np.zeros(len(self.all_vars))
        
        # Получаем текущий базис
        current_basis = self.basic_vars[-1]
        
        # Для каждой базисной переменной находим ее значение
        for i, var_name in enumerate(current_basis):
            if i < len(table):
                # Находим индекс переменной в all_vars
                if var_name in self.all_vars:
                    var_index = self.all_vars.index(var_name)
                    solution[var_index] = table[i, 0]
        
        # Значение целевой функции
        optimal_value = table[-1, 0]
        if not maximize:
            optimal_value = -optimal_value
        
        return solution, optimal_value


